app.post("/api/register", async (req,res) => {
  const {name, email, password} = req.body;
  if (!name || !email || !password) return res.status(400).json({error:"Барлық жолды толтырыңыз"});
  const key = email.trim().toLowerCase();
  if (users.has(key)) return res.status(409).json({error:"Бұл email бұрын тіркелген"});
  const hash = await bcrypt.hash(password, 10);
  users.set(key, {name:name.trim(), email:key, password:hash});
  req.session.user = {name:name.trim(), email:key};
  res.json({user:req.session.user});
});

app.post("/api/login", async (req,res) => {
  const {email,password} = req.body;
  const user = users.get((email||"").trim().toLowerCase());
  if (!user || !(await bcrypt.compare(password||"", user.password))) {
    return res.status(401).json({error:"Email немесе пароль қате"});
  }
  req.session.user = {name:user.name, email:user.email};
  res.json({user:req.session.user});
});

app.post("/api/logout", (req,res) => {
  req.session.destroy(() => res.json({ok:true}));
});

app.get("/api/me", (req,res) => {
  res.json({user:req.session.user || null});
});

app.post("/api/results", (req,res) => {
  if (!req.session.user) return res.status(401).json({error:"Алдымен кіріңіз"});
  const score = Math.max(0, Math.min(25, Number(req.body.score) || 0));
  results.push({name:req.session.user.name, score, total:25, date:Date.now()});
  results.sort((a,b)=> b.score-a.score || a.date-b.date);
  res.json({ok:true});
});

app.get("/api/leaderboard", (req,res) => {
  res.json(results.slice(0,10));
});

app.get("*", (req,res) => {
  res.sendFile(path.join(__dirname,"public","index.html"));
});

app.listen(PORT, () => console.log(`QuizPro started: http://localhost:${PORT}`));
